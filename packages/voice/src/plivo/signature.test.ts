import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { computePlivoV3Signature, plivoV3Base, validatePlivoV3Signature } from "./signature.js";

interface FixtureEntry {
  name: string;
  method: string;
  url: string;
  params: Record<string, string | string[]>;
  nonce: string;
  authToken: string;
  base: string;
  signature: string;
}

const here = dirname(fileURLToPath(import.meta.url));
const fixture = JSON.parse(readFileSync(join(here, "__fixtures__", "signature-v3.json"), "utf8")) as {
  source: string;
  entries: FixtureEntry[];
};

describe("Plivo V3 signature: fixture generated by Plivo's Node SDK", () => {
  it("the fixture comes from the SDK and covers the required cases", () => {
    expect(fixture.source).toBe("plivo-sdk");
    const names = fixture.entries.map((e) => e.name).join("|");
    for (const needle of ["no URL query", "with a URL query", "no body params", "multi-valued", "non-ASCII", "explicit port"]) {
      expect(names).toContain(needle);
    }
  });

  for (const e of fixture.entries) {
    it(`reproduces: ${e.name}`, () => {
      expect(plivoV3Base(e.url, e.params)).toBe(e.base);
      expect(computePlivoV3Signature(e.authToken, e.url, e.params, e.nonce)).toBe(e.signature);
      expect(validatePlivoV3Signature({
        method: "POST", authToken: e.authToken, url: e.url, params: e.params, nonce: e.nonce, signatureHeader: e.signature,
      })).toBe(true);
    });
  }
});

describe("Plivo V3 signature: properties", () => {
  const token = ["fake", "plivo", "token"].join("-");
  const url = "https://kirie.example.com/voice/plivo/turn/abc123?z=9&a=1";
  const params = { CallUUID: "11111111-2222-3333-4444-555555555555", Speech: "hello there", From: "201001234567" };
  const nonce = "12345678901234567890";
  const sig = computePlivoV3Signature(token, url, params, nonce);
  const ok = (over: Partial<Parameters<typeof validatePlivoV3Signature>[0]>) =>
    validatePlivoV3Signature({ method: "POST", authToken: token, url, params, nonce, signatureHeader: sig, ...over });

  it("body param order does not matter", () => {
    const reordered = { From: params.From, Speech: params.Speech, CallUUID: params.CallUUID };
    expect(computePlivoV3Signature(token, url, reordered, nonce)).toBe(sig);
  });

  it("a changed param, nonce, URL or token fails", () => {
    expect(ok({})).toBe(true);
    expect(ok({ params: { ...params, Speech: "hello there!" } })).toBe(false);
    expect(ok({ params: { ...params, Extra: "1" } })).toBe(false);
    expect(ok({ nonce: "12345678901234567891" })).toBe(false);
    expect(ok({ url: "https://kirie.example.com/voice/plivo/turn/abc124?z=9&a=1" })).toBe(false);
    expect(ok({ url: "https://kirie.example.com/voice/plivo/turn/abc123?z=8&a=1" })).toBe(false);
    expect(ok({ authToken: `${token}x` })).toBe(false);
  });

  it("missing header, missing nonce, empty token fail", () => {
    expect(ok({ signatureHeader: undefined })).toBe(false);
    expect(ok({ signatureHeader: "" })).toBe(false);
    expect(ok({ nonce: undefined })).toBe(false);
    expect(ok({ authToken: "" })).toBe(false);
  });

  it("a header with two signatures matches on either", () => {
    const other = computePlivoV3Signature("another-fake-token", url, params, nonce);
    expect(ok({ signatureHeader: `${other},${sig}` })).toBe(true);
    expect(ok({ signatureHeader: `${sig}, ${other}` })).toBe(true);
    expect(ok({ signatureHeader: `${other},${other}` })).toBe(false);
  });

  it("a GET is refused even with a correct signature", () => {
    expect(ok({ method: "GET" })).toBe(false);
  });

  it("a malformed URL fails without throwing", () => {
    expect(ok({ url: "/relative/path" })).toBe(false);
  });
});
